CREATE TABLE pi2MembrosDosProjetos (
    ID_MEMBRO_PROJETO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PROJETO_ID        NUMBER NOT NULL,
    USUARIO_ID        NUMBER NOT NULL,
    DATA_VINCULACAO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    PAPEL_NO_PROJETO  VARCHAR2(10) DEFAULT 'MEMBRO' NOT NULL,

    CONSTRAINT PK_MEMBROS_PROJETOS PRIMARY KEY (ID_MEMBRO_PROJETO),
    CONSTRAINT FK_MEMBRO_PROJETO
        FOREIGN KEY (PROJETO_ID) REFERENCES pi2Projetos (ID_PROJETO),
    CONSTRAINT FK_MEMBRO_USUARIO
        FOREIGN KEY (USUARIO_ID) REFERENCES pi2Usuarios (ID_USUARIO),
    CONSTRAINT UQ_MEMBRO_PROJETO_USUARIO UNIQUE (PROJETO_ID, USUARIO_ID),
    CONSTRAINT CK_MEMBRO_PAPEL
        CHECK (PAPEL_NO_PROJETO IN ('LIDER', 'MEMBRO'))
);