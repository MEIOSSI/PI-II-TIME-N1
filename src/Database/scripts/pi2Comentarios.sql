CREATE TABLE pi2Comentarios (
    id_comentario     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    demanda_id        NUMBER NOT NULL,
    usuario_id        NUMBER NOT NULL,
    texto             CLOB NOT NULL,
    data_criacao      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_COMENTARIOS PRIMARY KEY (id_comentario),
    CONSTRAINT FK_COMENTARIO_DEMANDA
        FOREIGN KEY (demanda_id) REFERENCES pi2Demandas (id_demanda),
    CONSTRAINT FK_COMENTARIO_USUARIO
        FOREIGN KEY (usuario_id) REFERENCES pi2Usuarios (id_usuario)
);

