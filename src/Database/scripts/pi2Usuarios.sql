CREATE TABLE pi2Usuarios (
    ID_USUARIO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME             VARCHAR2(120) NOT NULL,
    EMAIL            VARCHAR2(254) NOT NULL,
    SENHA            VARCHAR2(255) NOT NULL,
    PERFIL           VARCHAR2(20) DEFAULT 'USUARIO' NOT NULL,
    ATIVO            CHAR(1) DEFAULT 'S' NOT NULL,
    DATA_CRIACAO     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_PERFIL
        CHECK (PERFIL IN ('ADMINISTRADOR', 'USUARIO')),
    CONSTRAINT CK_USUARIOS_ATIVO
        CHECK (ATIVO IN ('S', 'N'))
);  