CREATE TABLE pi2Projetos (
    id_projeto       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    titulo           VARCHAR2(150) NOT NULL,
    descricao        CLOB,
    data_criacao     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    lider            NUMBER NOT NULL,
    criado_por       NUMBER NOT NULL,
    ativo            CHAR(1) DEFAULT 'S' NOT NULL,

    CONSTRAINT PK_PROJETOS PRIMARY KEY (id_projeto),
    CONSTRAINT FK_PROJETO_LIDER
        FOREIGN KEY (lider) REFERENCES pi2Usuarios (id_usuario),
    CONSTRAINT FK_PROJETO_CRIADOR
        FOREIGN KEY (criado_por) REFERENCES pi2Usuarios (id_usuario),
    CONSTRAINT CK_PROJETOS_ATIVO 
        CHECK (ativo IN ('S', 'N'))
);
