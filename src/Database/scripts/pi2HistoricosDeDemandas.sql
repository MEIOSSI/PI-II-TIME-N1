CREATE TABLE pi2HistoricosDeDemandas (
    id_historico       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    demanda_id         NUMBER NOT NULL,
    usuario_id         NUMBER NOT NULL,
    campo_alterado     VARCHAR2(40) NOT NULL,
    valor_anterior     VARCHAR2(4000),
    valor_novo         VARCHAR2(4000),
    data_alteracao     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_HISTORICOS_DEMANDAS PRIMARY KEY (id_historico),
    CONSTRAINT FK_HISTORICO_DEMANDA
        FOREIGN KEY (demanda_id) REFERENCES pi2Demandas (id_demanda),
    CONSTRAINT FK_HISTORICO_USUARIO
        FOREIGN KEY (usuario_id) REFERENCES pi2Usuarios (id_usuario),
    CONSTRAINT CK_HISTORICO_CAMPO
        CHECK (campo_alterado IN
            ('status', 'RESPONSAVEL', 'prioridade', 'prazo_final',
             'titulo', 'descricao', 'tipo'))
);