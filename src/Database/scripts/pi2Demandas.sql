CREATE TABLE pi2Demandas (
    ID_DEMANDA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO              VARCHAR2(200) NOT NULL,
    DESCRICAO           CLOB NOT NULL,
    TIPO                VARCHAR2(20) NOT NULL,
    PRIORIDADE          VARCHAR2(10) DEFAULT 'MEDIA' NOT NULL,
    STATUS              VARCHAR2(20) DEFAULT 'ABERTA' NOT NULL,
    DATA_CRIACAO        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DATA_ATUALIZACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    PRAZO_FINAL         DATE,
    PROJETO_ID          NUMBER NOT NULL,
    CRIADO_POR          NUMBER NOT NULL,
    RESPONSAVEL_ID      NUMBER,
    ATIVO               CHAR(1) DEFAULT 'S' NOT NULL,

    CONSTRAINT PK_DEMANDAS PRIMARY KEY (ID_DEMANDA),
    CONSTRAINT FK_DEMANDA_PROJETO
        FOREIGN KEY (PROJETO_ID) REFERENCES pi2Projetos (ID_PROJETO),
    CONSTRAINT FK_DEMANDA_CRIADOR
        FOREIGN KEY (CRIADO_POR) REFERENCES pi2Usuarios (ID_USUARIO),
    CONSTRAINT FK_DEMANDA_RESPONSAVEL
        FOREIGN KEY (RESPONSAVEL_ID) REFERENCES pi2Usuarios (ID_USUARIO),
    CONSTRAINT CK_DEMANDA_TIPO
        CHECK (TIPO IN ('TAREFA', 'DEFEITO', 'MELHORIA', 'DOCUMENTACAO')),
    CONSTRAINT CK_DEMANDA_PRIORIDADE
        CHECK (PRIORIDADE IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA')),
    CONSTRAINT CK_DEMANDA_STATUS
        CHECK (STATUS IN ('ABERTA', 'EM ANDAMENTO', 'EM REVISAO',
                          'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT CK_DEMANDA_ATIVO
        CHECK (ATIVO IN ('S', 'N'))
);